CREATE TABLE app_user (
    id   BIGINT PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    role VARCHAR(20)  NOT NULL
);

CREATE TABLE transcription_request (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT       NOT NULL REFERENCES app_user (id),
    title        VARCHAR(255) NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_request_owner ON transcription_request (owner_id);

CREATE TABLE document (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id        BIGINT       NOT NULL REFERENCES transcription_request (id),
    original_filename VARCHAR(500) NOT NULL,
    content_type      VARCHAR(255),
    storage_key       VARCHAR(255) NOT NULL,
    size_bytes        BIGINT       NOT NULL,
    status            VARCHAR(20)  NOT NULL,
    failure_reason    VARCHAR(1000),
    uploaded_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_document_request ON document (request_id);
CREATE INDEX idx_document_status ON document (status);

CREATE TABLE transcription (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id        BIGINT      NOT NULL UNIQUE REFERENCES document (id),
    request_id         BIGINT      NOT NULL REFERENCES transcription_request (id),
    owner_id           BIGINT      NOT NULL REFERENCES app_user (id),
    current_version_id BIGINT,
    review_status      VARCHAR(20) NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_transcription_owner ON transcription (owner_id);

CREATE TABLE transcription_version (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transcription_id BIGINT      NOT NULL REFERENCES transcription (id),
    version_no       INT         NOT NULL,
    content          TEXT        NOT NULL,
    source           VARCHAR(20) NOT NULL,
    author_id        BIGINT REFERENCES app_user (id),
    comment          VARCHAR(2000),
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_version UNIQUE (transcription_id, version_no)
);

CREATE TABLE escalation (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transcription_id BIGINT      NOT NULL REFERENCES transcription (id),
    escalated_by     BIGINT      NOT NULL REFERENCES app_user (id),
    escalated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_to      BIGINT REFERENCES app_user (id),
    status           VARCHAR(20) NOT NULL
);
CREATE INDEX idx_escalation_status ON escalation (status);

CREATE TABLE audit_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT,
    entity_type VARCHAR(50) NOT NULL,
    entity_id   BIGINT      NOT NULL,
    action      VARCHAR(50) NOT NULL,
    detail      VARCHAR(2000),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
