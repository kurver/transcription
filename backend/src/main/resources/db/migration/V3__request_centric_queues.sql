-- Request metadata
ALTER TABLE transcription_request ADD COLUMN case_id VARCHAR(100);
ALTER TABLE transcription_request ADD COLUMN case_owner VARCHAR(200);
ALTER TABLE transcription_request ADD COLUMN due_date DATE;
ALTER TABLE transcription_request ADD COLUMN priority VARCHAR(20) DEFAULT 'NORMAL' NOT NULL;

CREATE TABLE request_attribute (
    request_id BIGINT       NOT NULL REFERENCES transcription_request (id),
    attr_key   VARCHAR(100) NOT NULL,
    attr_value VARCHAR(1000),
    PRIMARY KEY (request_id, attr_key)
);

-- Specialist work is now per request (shared queue), replacing per-document escalations
CREATE TABLE specialist_task (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id   BIGINT       NOT NULL REFERENCES transcription_request (id),
    created_by   BIGINT       NOT NULL REFERENCES app_user (id),
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_to  BIGINT REFERENCES app_user (id),
    status       VARCHAR(20)  NOT NULL,
    source       VARCHAR(20)  NOT NULL,
    reason       VARCHAR(1000),
    completed_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_task_status ON specialist_task (status);
CREATE INDEX idx_task_request ON specialist_task (request_id);

INSERT INTO specialist_task (request_id, created_by, created_at, assigned_to, status, source)
    SELECT t.request_id, e.escalated_by, e.escalated_at, e.assigned_to, e.status, 'USER_REQUEST'
    FROM escalation e JOIN transcription t ON t.id = e.transcription_id;

DROP TABLE escalation;
ALTER TABLE transcription DROP COLUMN review_status;

-- QA: document-level reviews on a shared queue; sampling is decided once per transcription
ALTER TABLE transcription ADD COLUMN qa_sampled BOOLEAN DEFAULT FALSE NOT NULL;
UPDATE transcription SET qa_sampled = TRUE;   -- existing transcriptions are not retro-sampled

CREATE TABLE qa_review (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transcription_id    BIGINT      NOT NULL REFERENCES transcription (id),
    request_id          BIGINT      NOT NULL REFERENCES transcription_request (id),
    source              VARCHAR(30) NOT NULL,
    requested_by        BIGINT REFERENCES app_user (id),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    assigned_to         BIGINT REFERENCES app_user (id),
    status              VARCHAR(20) NOT NULL,
    reviewed_version_no INT,
    comment             VARCHAR(2000),
    completed_at        TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_qa_status ON qa_review (status);
CREATE INDEX idx_qa_request ON qa_review (request_id);
